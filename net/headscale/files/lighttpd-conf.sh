#!/bin/sh
# Prints configuration of the dedicated lighttpd instance serving headscale.
# This configuration is deliberately self-contained and never includes
# /etc/lighttpd/conf.d so nothing but headscale can be reached through it.

opt() {
	local v
	v="$(uci -q get "headscale.$1.$2")"
	echo "${v:-$3}"
}

server_url="$(opt main server_url)"
host="${server_url#https://}"
host="${host%%/*}"
host="${host%%:*}"
case "$host" in
	""|*[!A-Za-z0-9.-]*) echo "invalid server_url" >&2; exit 1 ;;
esac

listen_port="$(opt main listen_port 8080)"
http_port="$(opt lighttpd http_port 8081)"
https_port="$(opt lighttpd https_port 8443)"

conf_dir=/var/etc/headscale
cert="/etc/ssl/acme/$host.fullchain.crt"
key="/etc/ssl/acme/$host.key"
if [ ! -f "$cert" ] || [ ! -f "$key" ]; then
	# Self-signed certificate until Let's Encrypt one is issued
	cert="$conf_dir/selfsigned.pem"
	key="$cert"
	if [ ! -f "$cert" ]; then
		mkdir -p "$conf_dir"
		(umask 077; openssl req -new -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 \
			-sha256 -x509 -nodes -days 3650 -subj "/CN=$host" \
			-out "$cert" -keyout "$cert") >/dev/null 2>&1 || exit 1
	fi
fi

# http_block SOCKET
http_block() {
	cat <<EOF
\$SERVER["socket"] == "$1" {
	\$HTTP["host"] == "$host" {
		url.access-deny = ()
		\$HTTP["url"] =~ "^/\\\\.well-known/acme-challenge/[A-Za-z0-9_-]+\$" {
			alias.url = ( "/.well-known/acme-challenge/" => "/var/run/acme/challenge/" )
		} else {
			url.redirect = ( "^/(.*)" => "https://$host/\$1" )
			url.redirect-code = 301
		}
	}
}
EOF
}

# Tailscale clients don't need the REST admin API, API docs or version info.
# They are hidden from the internet unless explicitly enabled.
deny_admin=""
if [ "$(opt lighttpd remote_api 0)" != 1 ]; then
	deny_admin='		$HTTP["url"] =~ "^/(api/|swagger|version)" {
			url.access-deny = ( "" )
		}'
fi

# https_block SOCKET
https_block() {
	cat <<EOF
\$SERVER["socket"] == "$1" {
	ssl.engine = "enable"
	ssl.pemfile = "$cert"
	ssl.privkey = "$key"
	ssl.openssl.ssl-conf-cmd = ("MinProtocol" => "TLSv1.2")
	\$HTTP["host"] == "$host" {
		url.access-deny = ()
$deny_admin
		proxy.server = ( "" => (( "host" => "127.0.0.1", "port" => $listen_port )) )
		proxy.header = ( "upgrade" => "enable" )
		proxy.forwarded = ( "for" => 1, "proto" => 1 )
	}
}
EOF
}

cat <<EOF
# Generated by $0, do not edit
server.modules = ( "mod_access", "mod_alias", "mod_redirect", "mod_proxy", "mod_openssl" )
server.document-root = "/var/empty"
# Turris OS has no dedicated lighttpd user, the system lighttpd runs as root too
server.username = ""
server.groupname = ""
server.port = $http_port
server.use-ipv6 = "enable"
server.errorlog-use-syslog = "enable"
server.tag = ""
# HTTP/1.1 only, Tailscale control protocol needs connection upgrade
server.feature-flags += ( "server.h2proto" => "disable" )
# Everything is denied unless a block below for the headscale host allows it
url.access-deny = ( "" )

EOF

http_block ":$http_port"
http_block "[::]:$http_port"
https_block ":$https_port"
https_block "[::]:$https_port"
